// Builds MatePuzzleBank.Data.cs and docs/MATE_PUZZLES.md from the verified selection.
// Usage: node build-bank.mjs <selected.json> <crosscheck-out.json> <MatePuzzleBank.Data.cs> <MATE_PUZZLES.md>
import fs from 'node:fs';
import { Chess } from 'chess.js';

const [selFile, ccFile, csOut, mdOut] = process.argv.slice(2);
const selected = JSON.parse(fs.readFileSync(selFile, 'utf8'));
const provisional = process.env.PROVISIONAL === '1';
// ccFile may list several cross-check outputs (comma separated); a later file fills keys an earlier one missed.
// manual.json adds games that were matched by hand, with a note on how the second source records them.
const cross = new Map();
if (provisional) for (const s of selected) cross.set(s.key, { gid: 'PENDING', white: null, black: null, event: null, source: null });
else for (const f of ccFile.split(',')) for (const r of JSON.parse(fs.readFileSync(f, 'utf8'))) if (r.match && !cross.get(r.key)) cross.set(r.key, r.match);
const manual = fs.existsSync('manual.json') ? JSON.parse(fs.readFileSync('manual.json', 'utf8')) : { matches: {}, notes: {} };
for (const [k, v] of Object.entries(manual.matches || {})) if (!cross.get(k)) cross.set(k, v);
const notes = manual.notes || {};
// Games the second source did not confirm (any cross-check run; "White|Black|Site|k" keys), listed in the docs.
const dropped = [];
if (!provisional)
  for (const f of ccFile.split(','))
    for (const r of JSON.parse(fs.readFileSync(f, 'utf8')))
      if (!r.match && !cross.get(r.key) && r.rows !== 0) { // 0 rows = the site was rate-limiting, not a mismatch
        const [w, b] = r.key.split('|');
        const label = `${w.split(',')[0].trim()}–${b.split(',')[0].trim()}`;
        if (!dropped.includes(label)) dropped.push(label);
      }

const ascii = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '');
const given = n => { n = n.trim(); const i = n.indexOf(','); return i < 0 ? n : `${n.slice(i + 1).trim()} ${n.slice(0, i).trim()}`; };
const surname = n => ascii(n.split(',')[0].trim().split(/\s+/).pop()).toLowerCase();
const cs = s => JSON.stringify(s);

const rows = [];
for (const s of selected) {
  const match = cross.get(s.key);
  if (!match) { console.error(`NOT CROSS-CHECKED: ${s.key}`); process.exitCode = 2; continue; }

  // queen sacrifice: one of the player's queen moves is captured at once
  const chess = new Chess();
  for (let i = 0; i < s.startPly; i++) chess.move(s.moves[i]);
  let queenSac = false, sacrifice = false, kingMates = false;
  for (let i = 0; i < s.solution.length; i += 2) {
    const m = chess.move(s.solution[i]);
    if (i + 1 < s.solution.length) {
      const r = chess.move(s.solution[i + 1]);
      if (r.captured && r.to === m.to) sacrifice = true;
      if (m.piece === 'q' && r.captured && r.to === m.to) queenSac = true;
    } else if (m.piece === 'k') kingMates = true; // a discovered mate by a king move: the least obvious kind
  }
  const difficulty = s.k === 2 ? 'Easy' : queenSac ? 'Hard' : 'Standard';
  const year = (s.date || '').slice(0, 4);
  // display names: chessgames' spelling unless it is very long (e.g. Kieseritzky's four given names)
  const name = (cg, pm) => ascii(cg && cg.length <= 28 ? cg : given(pm));
  const white = name(match.white, s.white);
  const black = name(match.black, s.black);
  rows.push({
    id: `${year}-${surname(s.white)}-${surname(s.black)}-m${s.k}`,
    title: s.title, white, black, event: ascii(match.event || s.event), site: ascii(s.site.trim()), year,
    result: s.result, source: s.source, file: s.file, gid: match.gid, csSource: match.source, csEvent: match.event,
    k: s.k, difficulty, queenSac, sacrifice, kingMates, blackWins: s.result === '0-1', legal: s.legalAtStart, startPly: s.startPly, fen: s.fen.split(' ').slice(0, 4).join(' '),
    moves: s.moves, solution: s.solution, allChecks: s.allAttackerChecks, defReplies: s.steps[0].defenderReplies,
    identical: !match.note, note: notes[s.key] || match.note || null,
  });
}
const order = { Easy: 0, Standard: 1, Hard: 2 };
// Teaching order inside a band (the adventure deals the table top to bottom): plain mates before sacrifices, a
// king-move discovered mate last, White to move (board not flipped) before Black, then fewer legal moves first.
const teach = r => (r.sacrifice ? 2 : 0) + (r.kingMates ? 4 : 0) + (r.blackWins ? 1 : 0);
rows.sort((a, b) => order[a.difficulty] - order[b.difficulty] || a.k - b.k || teach(a) - teach(b) || a.legal - b.legal);

// ---- C#
let cdata = `using Ronriku.Domain.Puzzles;

namespace Ronriku.Domain.Chess
{
    // GENERATED by tools/mate-puzzles/build-bank.mjs from games that were mined from the pgnmentor.com collections and
    // re-found on chessgames.com with the same moves (a "Note:" in Source explains any difference in how the second
    // source records the game). Do not edit by hand; see docs/MATE_PUZZLES.md and tools/mate-puzzles/README.md.
    public static partial class MatePuzzleBank
    {
        private static readonly MatePuzzle[] Puzzles =
        {
`;
for (const r of rows) {
  const src = `pgnmentor.com ${r.file}; chessgames.com gid ${r.gid}${r.csSource ? ' (' + r.csSource + ')' : ''}${r.note ? '. Note: ' + r.note : ''}`;
  cdata += `            new MatePuzzle(${cs(r.id)}, ${r.title ? cs(r.title) : 'null'}, ${cs(r.white)}, ${cs(r.black)}, ${cs(r.event)}, ${cs(r.site)}, ${cs(r.year)}, ${cs(r.result)},
                ${cs(src)},
                ${r.k}, PuzzleDifficulty.${r.difficulty}, ${r.startPly}, ${cs(r.fen)},
                ${cs(r.moves.join(' '))}),
`;
}
cdata += `        };
    }
}
`;
fs.writeFileSync(csOut, cdata);

// ---- docs
const link = gid => `[${gid}](https://www.chessgames.com/perl/chessgame?gid=${gid})`;
let md = `# Checkmate puzzles: the real games

Every "BIG CARD · CHECKMATE" in a battle is a position from a game that was really played. The puzzle starts 2–3 of the winner's moves before the end of the game; the player makes the winner's moves, and the opponent answers with the moves that were actually played. **Nothing here is composed or invented.**

How each game was verified (all automated, scripts in \`tools/mate-puzzles/\`):

1. **Mined from a game database.** ${selected.length ? 'Games come from the free pgnmentor.com player collections' : ''} (17,089 games of 23 famous players were scanned; 413 end in checkmate). Only games whose last move is checkmate, with a decisive result, were considered.
2. **Re-found in a second, independent database.** Each chosen game was located on chessgames.com and its complete move list compared move by move with the first source: identical for ${rows.filter(r => r.identical).length} of ${rows.length}${rows.some(r => !r.identical) ? '; the exception is explained under *Notes*' : ''}. The chessgames.com game id is listed below. Candidates that could not be found there with the same moves were dropped (${dropped.join(', ')}), and candidates whose check could not be completed (the site rate-limits) were not used.
3. **Legality and mate are proven by two engines.** chess.js (an independent library) and the game's own engine (\`Domain/Chess\`, validated with the standard perft node counts) both replay the whole game with every move legal and reach checkmate. EditMode tests (\`MatePuzzleTests\`) repeat this for every shipped puzzle at every build.
4. **One solution only.** An exhaustive search proves that at each of the player's steps exactly **one** move forces mate within the remaining moves, and that no faster mate exists. Several well-known finishes were rejected because they fail this (for example the Levitsky–Marshall "gold coins" game ended by resignation, the Lasker–Thomas 1912 finish has alternative mates, and Légal's trap only works if the opponent errs).

The player always moves the winning side. Wrong (legal) moves are taken back with a short explanation; three wrong moves end the card.

| # | Level | Mate in | Game | Event · place · year | Result | Solution | Checks only | Sources |
|---|---|---|---|---|---|---|---|---|
`;
rows.forEach((r, i) => {
  const name = r.title ? `**${r.title}**: ` : '';
  md += `| ${i + 1} | ${r.difficulty} | ${r.k} | ${name}${r.white} – ${r.black} | ${r.event} · ${r.site} · ${r.year} | ${r.result} | \`${r.solution.join(' ')}\` | ${r.allChecks ? 'yes' : 'no'} | pgnmentor \`${r.file}\`; chessgames ${link(r.gid)} |\n`;
});
md += `
${rows.some(r => r.note) ? '## Notes\n\n' + rows.filter(r => r.note).map(r => `- **${r.title || r.white + ' – ' + r.black}**: ${r.note}`).join('\n') + '\n\n' : ''}"Level" is the difficulty band: *Easy* = mate in 2; *Standard* = mate in 3; *Hard* = mate in 3 that includes a queen sacrifice. In the adventure the 25 checkmate fights (4 battles and the boss of each world, in play order) walk this table from top to bottom, so difficulty only grows and, with at least 25 puzzles, no game is dealt twice; spare puzzles stay in reserve, chosen evenly among the untitled games, so the famous named games are always played (see \`LevelModes.MatePuzzle\` and \`MatePuzzleBank.ForFight\`).

## Famous games

${rows.filter(r => r.title).map(r => `- **${r.title}**: ${r.white} – ${r.black}, ${r.site} ${r.year}.`).join('\n')}

The others are real tournament, match, casual or exhibition games (${Math.min(...rows.map(r => +r.year))}–${Math.max(...rows.map(r => +r.year))}), mostly won by world-class players of their time (players: ${[...new Set(rows.filter(r => !r.title).flatMap(r => [r.white, r.black]).map(n => n.replace(/\s*\(.*?\)/g, '').trim().split(' ').pop()))].join(', ')}) that are less famous as games; they are listed under their own names and are not presented as famous.

## Regenerating

See \`tools/mate-puzzles/README.md\`.
`;
fs.writeFileSync(mdOut, md);
console.log(`wrote ${rows.length} puzzles: ` + rows.map(r => `${r.difficulty[0]}${r.k}`).join(' '));
